package s3_access_key

import (
	"github.com/hashicorp/terraform-plugin-framework-validators/int64validator"
	"github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/boolplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/int64planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/truenas/terraform-provider-truenas/internal/normalize"
	"github.com/truenas/terraform-provider-truenas/internal/planmod"
)

func resourceSchema() schema.Schema {
	return schema.Schema{
		Description: "Manages a TrueNAS S3 access key (s3.accesskey; TrueNAS 27.0 and later): an access key id and secret " +
			"an account uses to sign S3 requests to the TrueNAS S3 service. The secret is either supplied write-only " +
			"(`secret_wo`, never stored in state) or generated by TrueNAS and stored once in `secret` (Sensitive) from " +
			"the create or rotate response; it is never read back from the API afterwards and is null after an import.",
		Attributes: map[string]schema.Attribute{
			"id": schema.Int64Attribute{
				Computed:      true,
				Description:   "Numeric identifier of the access key.",
				PlanModifiers: []planmodifier.Int64{int64planmodifier.UseStateForUnknown()},
			},
			"name": schema.StringAttribute{
				Required:    true,
				Description: "Human-readable name for the access key (1-200 characters).",
				Validators:  []validator.String{stringvalidator.LengthBetween(1, 200)},
			},
			"username": schema.StringAttribute{
				Required:    true,
				Description: "Account the access key belongs to. Create-only: changing it recreates the key.",
				PlanModifiers: []planmodifier.String{
					planmod.ReplaceFromKnownString(),
				},
			},
			"access_key": schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Access key id clients sign requests with (16-128 upper-case letters and digits). Generated when unset. Create-only: changing it recreates the key.",
				Validators:  []validator.String{stringvalidator.RegexMatches(accessKeyPattern, "must be 16-128 upper-case letters and digits")},
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
					planmod.ReplaceFromKnownString(),
				},
			},
			"secret": schema.StringAttribute{
				Computed:  true,
				Sensitive: true,
				Description: "The generated secret access key, stored from the create or rotate response only (TrueNAS returns it " +
					"to administrators on every read, but the provider never reads it back). Null when `secret_wo` supplied the " +
					"secret, and after an import. Planned unknown when rotate_version changes.",
				PlanModifiers: []planmodifier.String{secretFollowsRotate{}},
			},
			"secret_wo": schema.StringAttribute{
				Optional:    true,
				Sensitive:   true,
				WriteOnly:   true,
				Description: "Secret access key to set (16-128 printable ASCII characters). Write-only: used at create, never stored in state. Requires `secret_wo_version`. Omit to have TrueNAS generate the secret (see `secret`).",
				Validators: []validator.String{
					stringvalidator.LengthBetween(16, 128),
					stringvalidator.AlsoRequires(path.MatchRoot("secret_wo_version")),
				},
			},
			"secret_wo_version": schema.Int64Attribute{
				Optional: true,
				Description: "Version of `secret_wo`. Changing it recreates the key with the new secret (the API cannot set a chosen " +
					"secret on an existing key; use `rotate_version` for a generated one). Required when secret_wo is set.",
				Validators:    []validator.Int64{int64validator.AlsoRequires(path.MatchRoot("secret_wo"))},
				PlanModifiers: []planmodifier.Int64{planmod.ReplaceFromKnownInt64()},
			},
			"rotate_version": schema.Int64Attribute{
				Optional: true,
				Description: "Bump to rotate: TrueNAS generates a new secret under the same access key id (s3.accesskey.update rotate) " +
					"and the new value is stored in `secret`.",
			},
			"enabled": schema.BoolAttribute{
				Optional:      true,
				Computed:      true,
				Description:   "Whether the access key may be used; a disabled key is refused by the S3 service. Default true.",
				PlanModifiers: []planmodifier.Bool{boolplanmodifier.UseStateForUnknown()},
			},
			"expires_at": schema.StringAttribute{
				Optional:   true,
				CustomType: normalize.RFC3339Type{},
				Description: "RFC3339 timestamp after which the key expires; unset means never, and removing it makes an expiring " +
					"key non-expiring again. Any offset or fractional-second spelling of the same instant matches the server's UTC read-back.",
				PlanModifiers: []planmodifier.String{normalize.KeepStateIfEquivalent(normalize.RFC3339Type{})},
			},
			"manage_buckets": schema.BoolAttribute{
				Optional:      true,
				Computed:      true,
				Description:   "Whether this key may create and delete buckets through the S3 protocol (needs a managed_root_dataset on truenas_s3_config and an account allowed to do so). Default false.",
				PlanModifiers: []planmodifier.Bool{boolplanmodifier.UseStateForUnknown()},
			},
			"user_identifier": schema.StringAttribute{
				Computed:      true,
				Description:   "Stored account linkage: the numeric uid for a local account, a SID for a directory services one.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"local": schema.BoolAttribute{
				Computed:      true,
				Description:   "Whether the key belongs to a local user account.",
				PlanModifiers: []planmodifier.Bool{boolplanmodifier.UseStateForUnknown()},
			},
			"created_at": schema.StringAttribute{
				Computed:      true,
				Description:   "RFC3339 UTC timestamp of creation.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"last_used_at": schema.StringAttribute{
				Computed:    true,
				Description: "RFC3339 UTC time the S3 service last accepted a request signed with this key; null when never used.",
			},
			"status": schema.StringAttribute{
				Computed:    true,
				Description: "ENABLED, DISABLED or EXPIRED, as the S3 service sees the key.",
			},
		},
	}
}
